export function getProductKasapImage(sku: string, fallbackIndex?: number): string {
  let pos = 0
  if (typeof fallbackIndex === 'number' && fallbackIndex >= 0) {
    pos = fallbackIndex % KASAP_IMAGES.length
  } else {
    let hash = 0
    for (let i = 0; i < sku.length; i++) {
      hash = ((hash << 5) - hash) + sku.charCodeAt(i)
      hash |= 0
    }
    pos = Math.abs(hash) % KASAP_IMAGES.length
  }
  const filename = KASAP_IMAGES[pos]
  return `/api/kasap-image/${filename}`
}

