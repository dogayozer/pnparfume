function changeLanguage(lang) {
    if (!translations[lang]) return;
    localStorage.setItem('pien_lang', lang);
    
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang][key]) {
            // HTML içeren stringler için innerHTML, yoksa textContent kullanılabilir
            // Güvenlik için eğer çeviri HTML etiketi (<b>, <span>, vs) içeriyorsa innerHTML
            if (translations[lang][key].includes('<')) {
                el.innerHTML = translations[lang][key];
            } else {
                if(el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                    if (el.hasAttribute('placeholder')) {
                        el.setAttribute('placeholder', translations[lang][key]);
                    } else {
                        el.value = translations[lang][key];
                    }
                } else {
                    el.innerHTML = translations[lang][key];
                }
            }
        }
    });

    // Dil seçici butonun görselini güncelle
    const langBtn = document.getElementById('lang-btn-text');
    if(langBtn) {
        langBtn.textContent = lang.toUpperCase();
    }
}

document.addEventListener('DOMContentLoaded', () => {
    // Kayıtlı dili al veya varsayılan tr yap
    const savedLang = localStorage.getItem('pien_lang') || 'tr';
    changeLanguage(savedLang);
    
    // Dil menüsü için aktif sınıfı ayarlama
    const langSelector = document.getElementById('lang-selector');
    if(langSelector) {
        langSelector.value = savedLang;
        langSelector.addEventListener('change', (e) => {
            changeLanguage(e.target.value);
        });
    }
});
